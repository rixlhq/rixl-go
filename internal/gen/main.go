// Command gen prepares the OpenAPI spec for oapi-codegen and writes the
// generated half of the sdk.Client facade. It is driven by gen.sh.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

func main() {
	log.SetFlags(0)

	var (
		specIn   = flag.String("spec", "", "OpenAPI spec to read")
		specOut  = flag.String("spec-out", "", "prepared spec to write")
		pkgsOut  = flag.String("packages", "", "tag/package list to write")
		facadeIn = flag.String("facade", "", "tag/package list to build the facade from")
		out      = flag.String("out", "", "facade file to write")
		aliases  = flag.Bool("aliases", false, "alias model types the generated packages reference unqualified")
	)
	flag.Parse()

	var err error
	switch {
	case *aliases:
		err = writeAliases()
	case *facadeIn != "":
		err = writeFacade(*facadeIn, *out)
	default:
		err = prepare(*specIn, *specOut, *pkgsOut)
	}
	if err != nil {
		log.Fatal(err)
	}
}

// prepare rewrites operationIds into Go-safe names and records every tag that
// carries an operation.
func prepare(specPath, specOut, pkgsOut string) error {
	raw, err := os.ReadFile(specPath)
	if err != nil {
		return err
	}

	var doc yaml.Node
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return fmt.Errorf("parse spec: %w", err)
	}

	paths := mapValue(doc.Content[0], "paths")
	if paths == nil {
		return fmt.Errorf("%s: no paths", specPath)
	}

	seen := map[string]bool{}
	tags := map[string]bool{}
	for i := 1; i < len(paths.Content); i += 2 {
		item := paths.Content[i]
		for j := 1; j < len(item.Content); j += 2 {
			operation := item.Content[j]
			if id := mapValue(operation, "operationId"); id != nil {
				id.Value = shortOperationID(id.Value, seen)
			}
			if opTags := mapValue(operation, "tags"); opTags != nil {
				for _, tag := range opTags.Content {
					tags[tag.Value] = true
				}
			}
		}
	}

	prepared, err := yaml.Marshal(&doc)
	if err != nil {
		return fmt.Errorf("encode spec: %w", err)
	}
	if err := os.WriteFile(specOut, prepared, 0o644); err != nil {
		return err
	}

	packages, err := packageList(tags)
	if err != nil {
		return err
	}

	var b strings.Builder
	for _, p := range packages {
		fmt.Fprintf(&b, "%s\t%s\n", p.pkg, p.tag)
	}
	return os.WriteFile(pkgsOut, []byte(b.String()), 0o644)
}

// shortOperationID reduces "clientauth.v1.ClientCredentialService.MintClientToken"
// to "MintClientToken". oapi-codegen uses the operationId verbatim for request
// body type names, so dots reach Go identifiers and the package does not
// compile. Collisions keep more of the qualifier.
func shortOperationID(id string, seen map[string]bool) string {
	parts := strings.Split(id, ".")
	for start := len(parts) - 1; start >= 0; start-- {
		candidate := strings.Join(parts[start:], "")
		if !seen[candidate] {
			seen[candidate] = true
			return candidate
		}
	}
	for n := 2; ; n++ {
		candidate := fmt.Sprintf("%s%d", strings.Join(parts, ""), n)
		if !seen[candidate] {
			seen[candidate] = true
			return candidate
		}
	}
}

type pkgTag struct{ pkg, tag string }

var nonAlphanumeric = regexp.MustCompile(`[^a-z0-9]`)

func packageList(tags map[string]bool) ([]pkgTag, error) {
	packages := make([]pkgTag, 0, len(tags))
	byPackage := map[string][]string{}
	for tag := range tags {
		pkg := nonAlphanumeric.ReplaceAllString(strings.ToLower(tag), "")
		if pkg == "" {
			return nil, fmt.Errorf("tag %q has no usable package name", tag)
		}
		packages = append(packages, pkgTag{pkg: pkg, tag: tag})
		byPackage[pkg] = append(byPackage[pkg], tag)
	}
	for pkg, tagged := range byPackage {
		if len(tagged) > 1 {
			sort.Strings(tagged)
			return nil, fmt.Errorf("tags %v all map to package %q", tagged, pkg)
		}
	}
	sort.Slice(packages, func(i, j int) bool { return packages[i].pkg < packages[j].pkg })
	return packages, nil
}

const facadeHeader = `// Code generated by gen.sh; DO NOT EDIT.

package sdk

import (
%s
)

// resources holds one typed client per OpenAPI tag. Client embeds it, so each
// one is reachable as client.<Resource>.
type resources struct {
%s
}

func newResources(cfg config) (*resources, error) {
	var (
		r   resources
		err error
	)

%s	return &r, nil
}
`

const facadeConstructor = `	{
		opts := make([]%[1]s.ClientOption, 0, len(cfg.editors)+1)
		if cfg.httpClient != nil {
			opts = append(opts, %[1]s.WithHTTPClient(cfg.httpClient))
		}
		for _, edit := range cfg.editors {
			opts = append(opts, %[1]s.WithRequestEditorFn(edit))
		}
		if r.%[2]s, err = %[1]s.NewSimpleClient(baseURL, opts...); err != nil {
			return nil, err
		}
	}
`

func writeFacade(pkgsPath, outPath string) error {
	raw, err := os.ReadFile(pkgsPath)
	if err != nil {
		return err
	}

	var imports, fields, constructors strings.Builder
	for _, line := range strings.Split(strings.TrimSpace(string(raw)), "\n") {
		pkg, tag, ok := strings.Cut(line, "\t")
		if !ok {
			return fmt.Errorf("malformed package line %q", line)
		}
		field := fieldName(tag)
		fmt.Fprintf(&imports, "\t\"github.com/rixlhq/rixl-go/sdk/%s\"\n", pkg)
		fmt.Fprintf(&fields, "\t%s *%s.SimpleClient\n", field, pkg)
		fmt.Fprintf(&constructors, facadeConstructor, pkg, field)
	}

	facade := fmt.Sprintf(facadeHeader,
		strings.TrimRight(imports.String(), "\n"),
		strings.TrimRight(fields.String(), "\n"),
		constructors.String())
	return os.WriteFile(outPath, []byte(facade), 0o644)
}

var wordSeparator = regexp.MustCompile(`[^A-Za-z0-9]+`)

func fieldName(tag string) string {
	var b strings.Builder
	for _, word := range wordSeparator.Split(tag, -1) {
		if word != "" {
			b.WriteString(strings.ToUpper(word[:1]) + word[1:])
		}
	}
	return b.String()
}

var undefinedSymbol = regexp.MustCompile(`^(sdk/[^/]+)/[^:]+\.go:\d+:\d+: undefined: (\w+)$`)

// writeAliases covers a gap in models-package support: enum types used by
// parameters are declared in sdk/models but referenced unqualified from the tag
// packages. Each one the compiler reports gets an alias where it is used.
func writeAliases() error {
	declared, err := modelsDeclarations()
	if err != nil {
		return err
	}

	missing := map[string]map[string]bool{}
	build := exec.Command("go", "build", "./sdk/...")
	build.Env = append(os.Environ(), "GOWORK=off")
	output, err := build.CombinedOutput()
	if err == nil {
		return nil
	}

	for _, line := range strings.Split(string(output), "\n") {
		match := undefinedSymbol.FindStringSubmatch(strings.TrimSpace(line))
		if match == nil {
			continue
		}
		pkgDir, symbol := match[1], match[2]
		if !declared[symbol] {
			continue
		}
		if missing[pkgDir] == nil {
			missing[pkgDir] = map[string]bool{}
		}
		missing[pkgDir][symbol] = true
	}
	if len(missing) == 0 {
		return fmt.Errorf("go build failed with errors that are not missing model types:\n%s", output)
	}

	for pkgDir, symbols := range missing {
		names := make([]string, 0, len(symbols))
		for symbol := range symbols {
			names = append(names, symbol)
		}
		sort.Strings(names)

		var b strings.Builder
		fmt.Fprintf(&b, "// Code generated by gen.sh; DO NOT EDIT.\n\npackage %s\n\n", filepath.Base(pkgDir))
		b.WriteString("import \"github.com/rixlhq/rixl-go/sdk/models\"\n\n")
		for _, name := range names {
			fmt.Fprintf(&b, "type %s = models.%s\n", name, name)
		}
		if err := os.WriteFile(filepath.Join(pkgDir, "aliases.gen.go"), []byte(b.String()), 0o644); err != nil {
			return err
		}
	}
	return nil
}

var typeDeclaration = regexp.MustCompile(`(?m)^type (\w+) `)

func modelsDeclarations() (map[string]bool, error) {
	raw, err := os.ReadFile("sdk/models/models.gen.go")
	if err != nil {
		return nil, err
	}
	declared := map[string]bool{}
	for _, match := range typeDeclaration.FindAllStringSubmatch(string(raw), -1) {
		declared[match[1]] = true
	}
	return declared, nil
}

func mapValue(node *yaml.Node, key string) *yaml.Node {
	if node == nil || node.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(node.Content); i += 2 {
		if node.Content[i].Value == key {
			return node.Content[i+1]
		}
	}
	return nil
}
